def pct(x, d=1):
    return "" if pd.isna(x) else f"{100 * float(x):.{d}f}%"


def num(x, d=1):
    return f"{float(x):,.{d}f}"


def table(df):
    cols = list(df.columns)
    out = ["| " + " | ".join(map(str, cols)) + " |", "|" + "---|" * len(cols)]
    out += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(out)


def csv(name, **kw):
    return pd.read_csv(O / name, **kw)


def log_quote(prefix, sentences=None):
    """Verbatim line from ai_usage_log.md; with `sentences`, only its first n sentences followed by '...'."""
    for line in (ROOT / "ai_usage_log.md").read_text(encoding="utf-8").splitlines():
        if line.lstrip("- ").startswith(prefix):
            s = line.lstrip("- ").strip()
            if sentences:
                parts = re.split(r"(?<=[.:])\s+(?=[A-Z*`(])", s)
                if len(parts) > sentences:
                    s = " ".join(parts[:sentences]) + " ..."
            return "> " + s
    raise KeyError(prefix)


