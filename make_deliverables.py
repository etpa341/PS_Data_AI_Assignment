"""
make_deliverables.py - build deliverables/, a folder of COPIES of the final files a reviewer needs first.

Nothing is moved: every original stays where the scripts, README and report links expect it. Run this last,
after report.md, docs/report.pdf and the outputs are final, so the copies match the originals.

Copies (each byte-identical to its source except report.md, whose chart and appendix links are rewritten to the copies in this folder):
  report.pdf, report.md, the Q2 chart, the gold dataset, the data quality report, the data dictionary,
  and the key evaluation files. A README.md inside the folder says what each file is and names its source.

Stops, without writing anything, if: a source is missing; the gold file is over 10 MB (pass --include-large to
override); or deliverables/ exists but was not made by this script. It only WARNS if docs/report.pdf has an older
file time than report.md, because a git clone gives every file the same checkout time; rerun make_report_pdf.py
if the PDF was not rendered from the current report.md. Afterwards it verifies every copy against its source, that
all relative links in the folder resolve, and that no em or en dash is in the generated or copied markdown.
No API calls.

Run:  python make_deliverables.py [--include-large]
"""
import hashlib
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "deliverables"
NOTE = "These are copies generated by `make_deliverables.py`. The source of each is the file named beside it."
LARGE_MB = 10
EM, EN = chr(0x2014), chr(0x2013)     # em and en dash, written as code points so this file holds neither

IMG_SRC = "outputs/figures/q2_dissatisfied_by_group.png"
IMG_COPY = "q2_dissatisfied_by_group.png"

# (source in repo, name in deliverables/, what it is)
FILES = [
    ("docs/report.pdf", "report.pdf", "The report as a PDF (A4). Read this if the markdown looks raw."),
    ("report.md", "report.md", "The report in markdown. Only change from the source: the chart and appendix links point to the copies in this folder."),
    ("docs/appendix.md", "appendix.md", "Detail behind the report: the full data quality table, the evaluation detail and short notes cut from the report."),
    (IMG_SRC, IMG_COPY, "The Q2 chart shown in the report: dissatisfied share by month, Parramatta and Dandenong against the other 19 dealers."),
    ("data/gold/feedback_gold.csv", "feedback_gold.csv", "The final consolidated dataset: one row per feedback row (7,271), cleaned and redacted, with AI labels. It includes the 201 excluded rows, flagged excluded = True with the reason in the column exclude_reason; the 7,070 included rows (7,060 with a score) are the ones used in the analysis. Columns are in data_dictionary.md."),
    ("outputs/quality_report.md", "quality_report.md", "The data quality report: each validation rule with rows checked, rows failed and the action taken, plus the exclusions."),
    ("data_dictionary.md", "data_dictionary.md", "What every column of the dataset and the outputs means."),
    ("profiling/data_governance.xlsx", "data_governance.xlsx", "The profiling workbook: manifest of all 82 sheets, issues log (161), decisions D1 to D9, data requests and the verification plan."),
    ("prompts/classify_v1.txt", "classify_v1.txt", "The classification prompt sent to the model with each comment (version v1, never edited after evaluation)."),
    ("ai_usage_log.md", "ai_usage_log.md", "The AI usage record: what was delegated, how it was checked, where the AI was wrong, and a dated entry for every labelling step."),
    ("outputs/evaluation/evaluation_report.md", "evaluation/evaluation_report.md", "AI labels against the 120 blind hand labels: accuracy, kappa, per-theme precision and recall, confusion tables and 10 errors."),
    ("outputs/evaluation/per_theme.csv", "evaluation/per_theme.csv", "Precision, recall and F1 for each theme."),
    ("outputs/evaluation/per_sentiment.csv", "evaluation/per_sentiment.csv", "Precision, recall and F1 for each sentiment."),
    ("outputs/evaluation/theme_confusion.csv", "evaluation/theme_confusion.csv", "Hand theme against AI theme, counts."),
    ("outputs/evaluation/sentiment_confusion.csv", "evaluation/sentiment_confusion.csv", "Hand sentiment against AI sentiment, counts."),
    ("outputs/evaluation/errors.csv", "evaluation/errors.csv", "The 10 example disagreements, with the redacted comment and an automatic hint."),
    ("outputs/evaluation/voice_check.csv", "evaluation/voice_check.csv", "Staff write-up tag against the 30 hand voice labels."),
    ("outputs/evaluation/ringwood_d2.csv", "evaluation/ringwood_d2.csv", "Ringwood score (1 to 10) against AI sentiment."),
    ("outputs/evaluation/extra_check_summary.csv", "evaluation/extra_check_summary.csv", "Blind check of the AI's Vehicle or product and Other comments (precision only)."),
]


def sha(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def size(p):
    n = Path(p).stat().st_size
    return f"{n / 1048576:.1f} MB" if n >= 1048576 else f"{max(1, round(n / 1024))} KB"


def slug(h):
    return re.sub(r"[^\w\- ]", "", h.strip().lower()).replace(" ", "-")


def main():
    # ---- preconditions (nothing is written until all pass)
    missing = [s for s, _, _ in FILES if not (ROOT / s).exists()]
    if missing:
        sys.exit(f"missing source files: {missing}")
    warnings = []
    if (ROOT / "docs/report.pdf").stat().st_mtime < (ROOT / "report.md").stat().st_mtime:
        warnings.append("docs/report.pdf has an older file time than report.md. After a git clone that is normal; "
                        "otherwise run `python make_report_pdf.py` first so the PDF matches the current report.")
    gold_mb = (ROOT / "data/gold/feedback_gold.csv").stat().st_size / 1048576
    if gold_mb > LARGE_MB and "--include-large" not in sys.argv:
        sys.exit(f"the gold file is {gold_mb:.1f} MB (over {LARGE_MB} MB): decide whether to include it, then rerun with --include-large.")
    report = (ROOT / "report.md").read_bytes()          # bytes, so line endings are preserved
    old_link, new_link = f"]({IMG_SRC})".encode(), f"]({IMG_COPY})".encode()
    if report.count(old_link) != 1:
        sys.exit(f"report.md must contain the chart link {old_link.decode()} exactly once")
    app_old, app_new = b"](docs/appendix.md", b"](appendix.md"          # the report's appendix links
    report_copy = report.replace(old_link, new_link).replace(app_old, app_new)
    if OUT.exists():
        marker = OUT / "README.md"
        if not (marker.exists() and "make_deliverables.py" in marker.read_text(encoding="utf-8")):
            sys.exit("deliverables/ exists but was not made by this script; not overwriting it.")
        shutil.rmtree(OUT)

    # ---- build
    for src, dst, _ in FILES:
        d = OUT / dst
        d.parent.mkdir(parents=True, exist_ok=True)
        if src == "report.md":
            d.write_bytes(report_copy)
        else:
            shutil.copyfile(ROOT / src, d)
    rows = ["| File | What it is | Source in the repo | Size |", "|---|---|---|---|"]
    for src, dst, what in FILES:
        rows.append(f"| [{dst}]({dst}) | {what} | `{src}` | {size(OUT / dst)} |")
    readme = (
        "# Deliverables\n\n"
        "The final files a reviewer needs first, in one folder. Start with `report.pdf` (or `report.md`).\n\n"
        f"{NOTE}\n\n"
        "Paths in backticks in `report.md` and `appendix.md` (for example `outputs/q2_robustness.csv`) are paths in the repo, not in this folder; only the files listed below are copied here.\n\n"
        + "\n".join(rows) + "\n\n"
        "The code is the numbered scripts (`01_bronze.py` to `05_gold.py`) and `analysis.ipynb` at the repo root.\n\n"
        "The rest of the repo is how these were built: see the main [README](../README.md) for the pipeline, the repo map and how to rerun it.\n"
    )
    (OUT / "README.md").write_text(readme, encoding="utf-8", newline="")

    # ---- verify
    problems = []
    for src, dst, _ in FILES:
        if src == "report.md":
            if (OUT / dst).read_bytes() != report_copy:
                problems.append(f"{dst} differs from the source by more than the chart and appendix links")
        elif sha(ROOT / src) != sha(OUT / dst):
            problems.append(f"{dst} is not byte-identical to {src}")
    for md in sorted(p for p in OUT.rglob("*") if p.suffix in (".md", ".txt")):    # authored text; the CSV data keeps customers' own wording
        t = md.read_text(encoding="utf-8")
        if EM in t or EN in t:
            problems.append(f"{md.relative_to(OUT)} contains an em or en dash")
        for link in (re.findall(r"\]\(([^)\s]+)\)", t) if md.suffix == ".md" else []):
            if link.startswith(("http://", "https://")):
                continue
            path, _, frag = link.partition("#")
            target = (md.parent / path).resolve() if path else md
            if not target.exists():
                problems.append(f"{md.relative_to(OUT)}: broken link {link}")
            elif frag and target.suffix == ".md" and frag not in {slug(x.lstrip("#")) for x in target.read_text(encoding="utf-8").splitlines() if x.startswith("#")}:
                problems.append(f"{md.relative_to(OUT)}: broken anchor {link}")
    total = sum(f.stat().st_size for f in OUT.rglob("*") if f.is_file())
    print(f"wrote deliverables/: {len(FILES) + 1} files, {total / 1048576:.1f} MB; gold file {size(OUT / 'feedback_gold.csv')} ({gold_mb:.2f} MB)")
    for p in problems:
        print("  PROBLEM:", p)
    print("  [PASS] copies match their sources, links resolve, no em or en dashes" if not problems else "  [FAIL] see problems above")
    for w in warnings:
        print("  WARNING:", w)
    if problems:
        sys.exit(1)


if __name__ == "__main__":
    main()
